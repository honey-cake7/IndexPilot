import uuid
from collections import deque
from dataclasses import dataclass

from indexpilot.candidates.deduplication import compare_existing
from indexpilot.candidates.models import (
    CandidateDecision,
    CandidateEvidence,
    GenerationOptions,
    GenerationResult,
    OperatorClass,
)
from indexpilot.candidates.sql import candidate_key, definition
from indexpilot.schema.models import TableInfo
from indexpilot.sql.models import SQLAnalysis

MAX_ATTEMPTS = 4096
MAX_POOL = 512
REASON_PRIORITY = {
    "equality_order": 0,
    "equality_range": 1,
    "composite_equality": 2,
    "join_lookup": 3,
    "equality": 4,
    "range": 5,
    "ordering": 6,
}


@dataclass(frozen=True)
class CandidateSource:
    plan_id: uuid.UUID
    analysis: SQLAnalysis


def _rank(column):
    selectivity = column.statistics.uniform_equality_selectivity if column.statistics else None
    return (selectivity if selectivity is not None else 1.0, column.name)


def _proposals(source: CandidateSource, tables, classes, options, warnings):
    analysis = source.analysis
    for binding in sorted(analysis.relations, key=lambda relation: relation.alias):
        table = tables[binding.relation_oid]
        columns = {column.name: column for column in table.columns}
        usable = {name: column for name, column in columns.items() if column.type_oid in classes}
        constant, joins, ranges = set(), set(), set()
        for predicate in analysis.predicates:
            if not predicate.conjunction_only:
                warnings.add(
                    "OR/NOT predicate branches are excluded from initial filter combinations."
                )
                continue
            if predicate.kind == "join" and predicate.operator == "=":
                if predicate.join_type not in (None, "JOIN_INNER"):
                    warnings.add(
                        "Outer-join lookup candidates are not generated by the initial policy."
                    )
                    continue
                for column in (predicate.column, predicate.other_column):
                    if column and column.alias == binding.alias:
                        joins.add(column.name)
            elif predicate.column.alias == binding.alias and predicate.other_kind == "literal":
                if predicate.kind == "equality" and predicate.operator == "=":
                    constant.add(predicate.column.name)
                elif predicate.kind == "range":
                    ranges.add(predicate.column.name)
        for name in constant | joins | ranges:
            if name not in usable:
                warnings.add(
                    "A referenced column lacks a verified default B-Tree operator class; skipped."
                )
        equality = sorted(
            (constant | joins) & usable.keys(),
            key=lambda name: (name not in constant, _rank(columns[name])),
        )[:4]
        const_order = [name for name in equality if name in constant]
        range_order = sorted(
            (ranges - constant) & usable.keys(), key=lambda name: _rank(columns[name])
        )[:4]
        if len(constant | joins) > 4 or len(ranges) > 4:
            warnings.add(
                "Per-table search limits retain at most four equality/join and four range columns."
            )

        def make(names, reason, *, ordering=None, columns=columns, table=table, binding=binding):
            if not names or len(names) > options.max_columns or len(set(names)) != len(names):
                return None
            keys = []
            for name in names:
                order = (ordering or {}).get(name)
                keys.append(
                    candidate_key(
                        columns[name],
                        classes[columns[name].type_oid],
                        descending=order.direction == "desc" if order else False,
                        nulls_first=order.nulls_first if order else False,
                    )
                )
            messages = {
                "equality": "A direct equality predicate supports a bounded lookup candidate.",
                "range": "A direct range predicate supplies an ordered search key.",
                "join_lookup": "An inner equality join exposes a parameterized lookup column.",
                "composite_equality": "Equality lookup keys form a composite alternative.",
                "equality_range": "Equality/join lookup keys precede one range key.",
                "ordering": "Keys preserve the supported ORDER BY direction and NULL placement.",
                "equality_order": "Constant equality keys precede compatible ordering keys.",
            }
            return definition(table, keys), CandidateEvidence(
                plan_id=source.plan_id,
                alias=binding.alias,
                reason=reason,
                explanation=messages[reason],
            )

        for name in equality:
            yield make([name], "equality" if name in constant else "join_lookup")
        for name in range_order:
            yield make([name], "range")
        alternatives = [equality]
        if len(equality) > 1:
            alternatives.append([equality[1], equality[0], *equality[2:]])
        for keys in alternatives:
            if len(keys) > 1 and options.max_columns > 1:
                yield make(keys[: options.max_columns], "composite_equality")
            for range_name in range_order[:2]:
                for width in range(1, min(len(keys), options.max_columns - 1) + 1):
                    yield make([*keys[:width], range_name], "equality_range")
        orders = analysis.order_by
        if not orders:
            continue
        if any(order.column is None or order.column.alias != binding.alias for order in orders):
            warnings.add(
                "Cross-relation/computed ORDER BY patterns are excluded from ordering candidates."
            )
            continue
        order_map = {}
        for order in orders:
            if order.column.name not in constant:
                order_map.setdefault(order.column.name, order)
        order_names = list(order_map)
        if any(name not in usable for name in order_names):
            warnings.add("An ordering column lacks a verified default B-Tree operator class.")
            continue
        if len(order_names) > options.max_columns:
            warnings.add(
                "Full ORDER BY exceeds the key-width limit; no full-order match is proposed."
            )
            continue
        if order_names:
            yield make(order_names, "ordering", ordering=order_map)
            room = options.max_columns - len(order_names)
            if const_order and room > 0:
                yield make(
                    [*const_order[:room], *order_names], "equality_order", ordering=order_map
                )


def generate_candidates(
    sources: list[CandidateSource],
    tables: dict[int, TableInfo],
    classes: dict[int, OperatorClass],
    options: GenerationOptions,
) -> GenerationResult:
    warnings = set()
    pool = {}
    attempts = 0
    truncated = False
    iterators = deque(
        _proposals(source, tables, classes, options, warnings)
        for source in sorted(sources, key=lambda source: str(source.plan_id))
    )
    while iterators and attempts < MAX_ATTEMPTS:
        iterator = iterators.popleft()
        try:
            proposal = next(iterator)
        except StopIteration:
            continue
        iterators.append(iterator)
        if proposal is None:
            continue
        attempts += 1
        candidate, evidence = proposal
        if candidate.signature not in pool:
            if len(pool) >= MAX_POOL:
                truncated = True
                continue
            reason, indexes, overlap_warnings = compare_existing(
                candidate, tables[candidate.table_oid].indexes
            )
            pool[candidate.signature] = CandidateDecision(
                definition=candidate,
                status="rejected" if reason else "proposed",
                rejection_reason=reason,
                existing_indexes=indexes,
                warnings=overlap_warnings,
                evidence=[],
            )
        decision = pool[candidate.signature]
        if evidence not in decision.evidence:
            decision.evidence.append(evidence)
    truncated = truncated or bool(iterators)

    def rank(decision):
        return (
            -len({item.plan_id for item in decision.evidence}),
            min(REASON_PRIORITY[item.reason] for item in decision.evidence),
            len(decision.definition.keys),
            decision.definition.signature,
        )

    ordered = sorted(pool.values(), key=rank)
    proposed, rejected = [], []
    for decision in ordered:
        decision.evidence.sort(key=lambda item: (str(item.plan_id), item.alias, item.reason))
        if decision.status == "rejected":
            rejected.append(decision)
        elif len(proposed) < options.max_candidates:
            proposed.append(decision)
        else:
            rejected.append(
                decision.model_copy(
                    update={"status": "rejected", "rejection_reason": "candidate_limit"}
                )
            )
    if truncated:
        warnings.add(
            "Bounded enumeration was truncated; candidate/evidence coverage may be incomplete."
        )
    warnings.add(
        "Candidate priority uses query coverage and structural heuristics, not measured benefit."
    )
    warnings.add("Storage, planner benefit and write overhead have not been evaluated.")
    return GenerationResult(
        proposed=proposed,
        rejected=rejected,
        attempts=attempts,
        unique_considered=len(pool),
        search_truncated=truncated,
        warnings=sorted(warnings),
    )
